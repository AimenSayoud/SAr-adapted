"""X-099 — the benchmark baseline of the InSAR full test: the plain chain of consecutive pairs (T54) and fusion v3
at P6, scored by the common scorer (C-061) on the design years, by every view.

Every later test (X-085, X-089, X-093, X-094, the SLC pilot, v4) is compared with these tables, so they are made once,
by the same scorer, with the same protocol (hub ``08_deliverables/insar_full_test/protocol.yaml``). The pairs and the
laser are read exactly as X-082 reads them (consecutive pairs at the P6 cell, 40 m, both references); where its views
coincide the numbers are X-082's (the C-061 regression proves it).

Pre-registration: ``08_deliverables/insar_full_test/preregistration/X-099.yaml`` (checked before the run).
Reads the cube and the hub; writes only to the hub: ``08_deliverables/insar_full_test/baseline/``. No field value in
this file.

    make run E=baseline_x099
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import p6_validation_x082 as X  # noqa: E402  (the X-082 readers: pairs and laser, unchanged)

from insar_wetlands.paths import hub_root  # noqa: E402
from insar_wetlands.scoring import Protocol, assert_preregistered, detrended_stats, score  # noqa: E402

HUB = hub_root()
FT = HUB / "08_deliverables" / "insar_full_test"
OUT = FT / "baseline"
PREREG = FT / "preregistration" / "X-099.yaml"
PROTOCOL = FT / "protocol.yaml"


def baseline() -> dict[str, pd.DataFrame]:
    prot = Protocol.load(PROTOCOL)
    p, las = X.load_pairs(), X.laser()[0]
    tables: dict[str, list[pd.DataFrame]] = {}
    for track in X.TRACKS:
        lt = las[track].dropna()
        g = p[(p.track == track) & (p.t1 >= lt.index.min() - pd.Timedelta(days=13)) &
              (p.t2 <= lt.index.max() + pd.Timedelta(days=13))].sort_values("t1")
        for ref in X.REFS:
            r = score(g.assign(est_mm=g[f"s1_{ref}"], truth_inc_mm=g.d_laser_los_mm), lt, prot)
            for name, t in r.items():
                tables.setdefault(name, []).append(t.assign(estimate="plain chain", track=track, reference=ref))
    v3 = []
    if X.V3.exists():
        v = pd.read_csv(X.V3)
        v["time_utc"] = pd.to_datetime(v.time_utc, format="ISO8601", utc=True)
        _, lev = X.laser()
        for (run, variant), gg in v.groupby(["run", "variant"]):
            gg = gg.sort_values("time_utc").drop_duplicates("time_utc")
            lv = lev.reindex(gg.time_utc.dt.round("h")).to_numpy()
            m = np.isfinite(lv) & np.isfinite(gg.h_v3_mm.to_numpy())
            if m.sum() >= prot.min_epochs:
                v3.append({"estimate": "fusion v3", "run": run, "variant": variant,
                           **detrended_stats(gg.time_utc[m], lv[m], gg.h_v3_mm.to_numpy()[m])})
    out = {k: pd.concat(v, ignore_index=True) for k, v in tables.items()}
    out["fusion_v3"] = pd.DataFrame(v3)
    return out


def md(df: pd.DataFrame, cols: list[str], nd: int = 2) -> str:
    d = df[cols].copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda x: f"{x:.{nd}f}")
    return "\n".join(["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)] +
                     ["| " + " | ".join(str(x) for x in row) + " |" for row in d.itertuples(index=False)])


def readme(t: dict[str, pd.DataFrame]) -> str:
    lev = t["levels"]
    key = lev[lev.view.isin(["full span", "datum A", "datum B"])]
    return f"""# X-099 — baseline of the InSAR full test (generated)

Generated by `experiments/baseline_x099.py` (`make run E=baseline_x099`); do not edit. Pre-registration:
`../preregistration/X-099.yaml`. Scorer: `insar_wetlands.scoring` (C-061), protocol `../protocol.yaml`.

The **plain chain** is the cumulative phase of consecutive pairs at the P6 cell (40 m, both references), as T54 and
X-082. Every later test of the full test is compared with these tables (`levels.csv`, `winters.csv`,
`increments.csv`, `seasons.csv`, `years.csv`, `fusion_v3.csv`).

## Levels (detrended, per view)

{md(key, ["track", "reference", "view", "epochs", "pearson_detrended", "rmse_detrended_mm", "within_10mm", "amplitude_ratio"])}

## Across winters (level step, estimate − laser)

{md(t["winters"], ["track", "reference", "winter", "laser_change_mm", "insar_change_mm", "difference_mm", "same_segment"])}

## Increments

{md(t["increments"], ["track", "reference", "pairs", "pearson_increments", "rmse_increments_mm", "slope_through_origin", "within_quarter_wave"])}

## Year to year (increments: sign and slope of the relation)

{md(t["years"], ["track", "reference", "year", "pairs", "pearson_increments", "slope_through_origin", "sign"])}

## By season (increments)

{md(t["seasons"], ["track", "reference", "season", "pairs", "pearson_increments", "slope_through_origin"])}

## Fusion v3 at P6 (WP5 series, detrended)

{md(t["fusion_v3"], ["run", "variant", "epochs", "pearson_detrended", "rmse_detrended_mm"]) if len(t["fusion_v3"]) else "—"}
"""


def main() -> None:
    assert_preregistered(PREREG, [OUT / "levels.csv"])
    t = baseline()
    OUT.mkdir(parents=True, exist_ok=True)
    for name, df in t.items():
        df.to_csv(OUT / f"{name}.csv", index=False)
    (OUT / "README.md").write_text(readme(t), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
