"""X-109 — are the cube's HyP3 grids placed right? RTC backscatter and interferogram coherence against the LiDAR.

X-101's diagnosis found the HyP3 RTC ascending grid offset from the airborne LiDAR canopy beyond the layover a right
grid shows. Every plot- and pixel-level result sits on these grids, so each HyP3 product is placed against the LiDAR
canopy height (and WorldCover tree share), per track and year, by the rule fixed in the pre-registration
(``08_deliverables/insar_full_test/preregistration/X-109.yaml``): backscatter of a right grid shows bright canopy pulled
toward each sensor by a similar layover (east-west shifts of opposite sign, nearly cancelling); coherence (low on
trees, no layover brightening) should need no shift.

Reads only the cube; writes to the hub: ``08_deliverables/insar_full_test/hyp3_placement/``.

    make run E=hyp3_placement_x109
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr

sys.path.insert(0, str(Path(__file__).resolve().parent))
from slc_qc_x101 import CELL, best_shift  # noqa: E402  (the same shift search as X-101 QC v2)

from insar_wetlands.cube import cube_root  # noqa: E402
from insar_wetlands.paths import hub_root  # noqa: E402
from insar_wetlands.scoring import assert_preregistered  # noqa: E402

HUB = hub_root()
CUBE = cube_root()
FT = HUB / "08_deliverables" / "insar_full_test"
OUT = FT / "hyp3_placement"
PREREG = FT / "preregistration" / "X-109.yaml"
TOL_M = 20.0
TRACKS = ("ascending", "descending")
SUMMER = ("06", "07", "08")
IFG_SET = {2021: "2020_2021", 2023: "2022_2024"}


def rtc_image(track: str, year: int) -> np.ndarray:
    with xr.open_dataset(CUBE / "silver" / f"rtc_{track}.nc") as d:
        t = pd.to_datetime(d.time.values)
        sel = (t.year == year) & t.strftime("%m").isin(SUMMER)
        return np.nanmean(d.vv_db.values[sel], axis=0)


def coh_image(track: str, year: int) -> np.ndarray:
    with xr.open_dataset(CUBE / "silver" / f"ifg_{IFG_SET[year]}_{track}.nc") as d:
        t1, t2 = pd.to_datetime(d.t1.values), pd.to_datetime(d.t2.values)
        days = (t2 - t1).days
        sel = (t1.year == year) & t1.strftime("%m").isin(SUMMER) & (days <= 12)
        return -np.nanmean(d.coh.values[sel], axis=0)


def main() -> None:
    assert_preregistered(PREREG, [OUT / "placement.csv"])
    OUT.mkdir(parents=True, exist_ok=True)
    st = xr.open_dataset(CUBE / "silver" / "static_40m.nc")
    refs = {"lidar canopy p90": st.lidar_vegh_p90_m.values.astype(float), "worldcover tree": st.wc_tree.values.astype(float)}
    rows = []
    for product, fn in (("RTC backscatter", rtc_image), ("interferogram coherence", coh_image)):
        for year in (2021, 2023):
            for track in TRACKS:
                img = fn(track, year)
                for rname, ref in refs.items():
                    r, dy, dx = best_shift(img, ref)
                    rows.append({"product": product, "year": year, "track": track, "reference": rname,
                                 "dx_m": dx * CELL, "dy_m": -dy * CELL, "r": r})
    pl = pd.DataFrame(rows)
    pl.to_csv(OUT / "placement.csv", index=False)
    v = verdict(pl)
    v.to_csv(OUT / "verdict.csv", index=False)
    (OUT / "README.md").write_text(readme(pl, v), encoding="utf-8")
    print(v.to_string(index=False))
    print(f"wrote {OUT}")


def verdict(pl: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for (product, year), g in pl[pl.reference == "lidar canopy p90"].groupby(["product", "year"]):
        a, d = g.set_index("track").loc["ascending"], g.set_index("track").loc["descending"]
        if product == "RTC backscatter":
            ok = bool(np.sign(a.dx_m) != np.sign(d.dx_m) and abs(a.dx_m + d.dx_m) <= TOL_M
                      and abs(a.dy_m) <= TOL_M and abs(d.dy_m) <= TOL_M)
            asym = a.dx_m + d.dx_m
        else:
            ok = bool(max(abs(a.dx_m), abs(d.dx_m), abs(a.dy_m), abs(d.dy_m)) <= TOL_M)
            asym = np.nan
        rows.append({"product": product, "year": year, "dx_asc_m": a.dx_m, "dx_desc_m": d.dx_m,
                     "dx_asc_plus_desc_m": asym, "dy_asc_m": a.dy_m, "dy_desc_m": d.dy_m,
                     "placed_right": ok})
    return pd.DataFrame(rows)


def _md(df: pd.DataFrame, nd: int = 0) -> str:
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda x: "—" if pd.isna(x) else (f"{x:.2f}" if c == "r" else f"{x:+.{nd}f}"))
    return "\n".join(["| " + " | ".join(map(str, d.columns)) + " |", "|" + "---|" * len(d.columns)] +
                     ["| " + " | ".join(map(str, r)) + " |" for r in d.itertuples(index=False)])


def readme(pl: pd.DataFrame, v: pd.DataFrame) -> str:
    return f"""# X-109 — placement of the cube's HyP3 grids against the LiDAR (generated)

Generated by `experiments/hyp3_placement_x109.py` (`make run E=hyp3_placement_x109`); do not edit. Pre-registration:
`../preregistration/X-109.yaml`. dx/dy = the shift (m, east/north positive) that best aligns the HyP3 image with the
reference. Backscatter of a right grid: opposite-sign east-west shifts on the two tracks (layover toward each sensor),
|dx asc + dx desc| <= {TOL_M:.0f} m, |dy| <= {TOL_M:.0f} m. Coherence (minus mean, low on trees): |dx|, |dy| <= {TOL_M:.0f} m.

## Verdict (LiDAR canopy)

{_md(v)}

## Every product, year, track and reference

{_md(pl)}
"""


if __name__ == "__main__":
    main()
