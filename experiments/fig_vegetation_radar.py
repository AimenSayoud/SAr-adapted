def effects(outcome: str, variant: str = "primary") -> pd.DataFrame:
    """Rows: group, track, set, estimate, lo, hi — the contrasts of X-132 and X-134 for one outcome and variant
    ("primary", or a registered sensitivity such as "radius 500 m")."""
    s = pd.read_csv(X132 / "stage1.csv")
    s = s[(s.variant == variant) & (s.outcome == outcome) & s.contrast.isin(["on_mat", "off_mat"])]
    rows = [{"group": f"trees {'on' if r.contrast == 'on_mat' else 'off'} the mat\nwooded − open",
             "track": r.track, "set": r.set, "est": r.wooded_minus_open, "lo": r.lo95, "hi": r.hi95}
            for r in s.itertuples()]
    m = pd.read_csv(X134 / "matched.csv")
    m = m[(m.variant == variant) & (m.outcome == outcome)]
    rows += [{"group": "dense shrub − open\non the mat", "track": r.track, "set": r.set,
              "est": r.shrubby_minus_open, "lo": r.lo95, "hi": r.hi95} for r in m.itertuples()]
    d = pd.read_csv(X134 / "dose.csv")
    d = d[(d.variant == variant) & (d.outcome == outcome)]
    rows += [{"group": "shrub 0 → 15 %\non the mat", "track": r.track, "set": r.set,
              "est": r.effect_0_15, "lo": r.effect_lo95, "hi": r.effect_hi95} for r in d.itertuples()]
    out = pd.DataFrame(rows)
    return out[out.set.isin(SETS)]


def forest(ax, df: pd.DataFrame, xlabel: str, sets: list[str]) -> None:
    groups = list(dict.fromkeys(df.group))
    k = 0
    for gi, g in enumerate(groups):
        if gi % 2 == 0:
            ax.axhspan(gi - 0.5, gi + 0.5, color=fs.GRID, alpha=0.35, lw=0)
        for track in ("ascending", "descending"):
            for s in sets:
                r = df[(df.group == g) & (df.track == track) & (df.set == s)]
                if not len(r):
                    continue
                r = r.iloc[0]
                n = len(sets) * 2
                idx = (0 if track == "ascending" else len(sets)) + sets.index(s)
                y = gi - 0.36 + 0.72 * idx / (n - 1)
                ax.hlines(y, r.lo, r.hi, color=fs.TRACK[track], lw=1.1)
                ax.plot(r.est, y, SETS[s][1], ms=3.6, color=fs.TRACK[track], mec="white", mew=0.4)
                k += 1
    ax.axvline(0, color=fs.INK, lw=0.7)
    ax.set_yticks(range(len(groups)), groups, fontsize=7)
    ax.set_ylim(len(groups) - 0.5, -0.5)
    ax.set_xlabel(xlabel)
    ax.grid(axis="y", visible=False)


def grid_image(cells: pd.DataFrame, value, res=40.0):
    x0, x1, y0, y1 = cells.x.min(), cells.x.max(), cells.y.min(), cells.y.max()
    nx, ny = int(round((x1 - x0) / res)) + 1, int(round((y1 - y0) / res)) + 1
    img = np.full((ny, nx), np.nan)
    ix = np.round((cells.x - x0) / res).astype(int)
    iy = np.round((y1 - cells.y) / res).astype(int)
    img[iy, ix] = value
    return img, (x0 - res / 2, x1 + res / 2, y0 - res / 2, y1 + res / 2)


def ortho_rgb(box, res=0.2):
    """The 10 cm GUGiK orthophoto (EPSG:2180) resampled onto a UTM 33N grid over ``box`` (W, S, E, N)."""
    w, s, e, n = box
    tr = from_origin(w, n, res, res)
    shape = (int(round((n - s) / res)), int(round((e - w) / res)))
    out = np.zeros((3, *shape), dtype="float32")
    for f in sorted(ORTHO.glob("81270_*.tif")):
        with rasterio.open(f) as r:
            b = transform_bounds("EPSG:32633", r.crs, w, s, e, n)
            if b[2] < r.bounds.left or b[0] > r.bounds.right or b[3] < r.bounds.bottom or b[1] > r.bounds.top:
                continue
            win = rasterio.windows.from_bounds(*b, transform=r.transform).round_offsets().round_lengths()
            win = win.intersection(rasterio.windows.Window(0, 0, r.width, r.height))
            for i in range(3):
                a = r.read(i + 1, window=win).astype("float32")
                tmp = np.zeros(shape, dtype="float32")
                reproject(a, tmp, src_transform=r.window_transform(win), src_crs=r.crs, dst_transform=tr,
                          dst_crs="EPSG:32633", resampling=Resampling.average, src_nodata=0, dst_nodata=0)
                out[i] = np.where(tmp > 0, tmp, out[i])
    return np.clip(np.moveaxis(out, 0, -1) / 255.0, 0, 1), (w, e, s, n)


