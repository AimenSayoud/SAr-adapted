"""X-107 amendment_4 — the weather model alone: v4's frozen SPAMS, no radar, read at the chain's epochs.

The ablation of the article (§6.5) separates what the radar adds from what the weather adds: the plain chain (radar
within seasons and across winters), v4 (radar within seasons, SPAMS across winters) and SPAMS alone (weather in both).
``build_weather_only`` is what X-107 runs, once, on the held-out years with the frozen parameter file of X-106 (no
refit), scored like the other rows. Run here on the design years only — in-sample, like the freeze's own report — to
show that the row can be built with the frozen parameters as they stand (the amendment's condition); no held-out year
is read.

Reads the as-delivered cube snapshot (as the freeze did: X-107 amendment) and the hub; writes only to the hub.

    RZECIN_CUBE_ROOT=../../06_data/cube_snapshots/as_delivered_2026-10-15 make run E=weather_only_x107
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import freeze_v4_x106 as F  # noqa: E402  (build_v4, spams_level, DESIGN, the frozen parameter file)

from insar_wetlands import v4  # noqa: E402
from insar_wetlands.scoring import Protocol, assert_preregistered, detrended_stats, level_views, winter_steps  # noqa: E402

OUT = F.V4DIR / "weather_only_design"
PREREG = F.FT / "preregistration" / "X-107.yaml"
NAME = "weather model alone (SPAMS)"


def build_weather_only(track: str, frozen: dict, years: tuple[int, ...]) -> pd.DataFrame:
    """SPAMS's level (vertical mm) at the epochs of the plain chain of ``track`` over ``years``: time, seg, est."""
    c = F.build_v4(track, frozen, years, relevel=False)
    R = F.spams_level(frozen)
    at = lambda t: float(R.reindex([pd.Timestamp(t).tz_convert(None).normalize()]).iloc[0])
    return v4.anchor_only(c, at)


def score(c: pd.DataFrame, lev: pd.Series, prot: Protocol, track: str) -> tuple[list[dict], pd.DataFrame]:
    """The freeze's report for one series: season views (rmse_detrended_mm) and winter steps, against the laser."""
    c = c.copy()
    c["truth"] = lev.reindex(pd.DatetimeIndex(c.time).round("h")).to_numpy()
    rows = [{"track": track, "estimate": NAME, "view": view, **detrended_stats(dd.time, dd.truth, dd.est)}
            for view, dd in level_views(c, prot) if view.startswith("season") and len(dd) >= 4]
    z = c.dropna(subset=["truth"]).copy()
    for _, cs in z.groupby("seg"):
        z.loc[cs.index, "truth"] -= cs.truth.iloc[0]
        z.loc[cs.index, "est"] -= cs.est.iloc[0]
    return rows, winter_steps(z, prot).assign(track=track, estimate=NAME)


def main() -> None:
    assert_preregistered(PREREG, [OUT / "summary.csv"])
    OUT.mkdir(parents=True, exist_ok=True)
    prot = Protocol.load(F.FT / "protocol.yaml")
    frozen = yaml.safe_load(F.PARAMS.read_text(encoding="utf-8"))
    lev = F.X.laser()[1]
    rows, wins = [], []
    for track in F.X.TRACKS:
        r, w = score(build_weather_only(track, frozen, F.DESIGN), lev, prot, track)
        rows += r
        wins.append(w)
    S, W = pd.DataFrame(rows), pd.concat(wins, ignore_index=True)
    summ = (S.groupby(["estimate", "track"]).rmse_detrended_mm.median().rename("season_rmse_median_mm").to_frame()
            .join(W.assign(ae=W.difference_mm.abs()).groupby(["estimate", "track"]).ae.mean().rename("winter_mae_mm"))
            .reset_index())
    both = pd.concat([pd.read_csv(F.OUT / "summary.csv"), summ], ignore_index=True)
    for name, df in (("seasons", S), ("winters", W), ("summary", summ), ("ablation_design", both)):
        df.to_csv(OUT / f"{name}.csv", index=False)
    md = lambda df: "\n".join(["| " + " | ".join(map(str, df.columns)) + " |", "|" + "---|" * len(df.columns)] +
                              ["| " + " | ".join(f"{x:.2f}" if isinstance(x, float) else str(x) for x in r) + " |"
                               for r in df.itertuples(index=False)])
    (OUT / "README.md").write_text(f"""# The weather model alone — design years (generated, in-sample)

Generated by `experiments/weather_only_x107.py`; do not edit. X-107 amendment_4: v4's frozen SPAMS
(`../v4_frozen_params.yaml`, code sha {frozen['code_sha']}, no refit) read at the plain chain's epochs and scored by the
freeze's report. In-sample on the design years: SPAMS was fitted on them, so this only shows the row can be built with
the frozen parameters; the reported row is X-107's, on the held-out years. Vertical mm against the laser (as-delivered
snapshot, the freeze's laser rule).

## The ablation on the design years (v4 and the plain chain from `../design_report/summary.csv`)

{md(both)}

## Winter steps, weather alone

{md(W[['track', 'winter', 'laser_change_mm', 'insar_change_mm', 'difference_mm']])}
""", encoding="utf-8")
    print(both.to_string(index=False))


if __name__ == "__main__":
    main()
