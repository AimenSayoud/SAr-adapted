"""Colab launchers: one thin notebook per register entry that runs on Colab (``colab/<entry>.ipynb``).

The analysis lives in the entry's ``.py`` (``experiments/`` or ``pipelines/``), never in the notebook. The launcher
only mounts the Drive, checks out a pinned commit, installs, runs the entry through the register (which writes the
run record to Drive ``runs/<entry>/``), and shows the record. Generated, so every launcher is the same:

    python -m insar_wetlands.colab <entry> [--ref <branch or commit>] [--extra acquisition] [--pip "dolphin ..."]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from .register import REPO, load_register

REPO_URL = "https://github.com/AimenSayoud/SAr-adapted.git"
# what colab/requirements.txt gives a pip session, installed from conda-forge instead when the entry needs conda tools
CONDA_BASE = "xarray netcdf4 h5py rioxarray rasterio pyproj shapely pyyaml pandas scipy matplotlib requests"


def _md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip().splitlines(keepends=True)}


def _code(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": text.strip().splitlines(keepends=True)}


def launcher(entry: str, ref: str = "fusion-x062", extra: str = "", pip: str = "", args: str = "",
             conda: str = "", secrets: str = "") -> dict:
    e = load_register().get(entry)
    if e is None:
        raise SystemExit(f"no register entry {entry!r}")
    if e.runs_on != "colab":
        raise SystemExit(f"{entry} runs on the Mac (make run E={entry}); no launcher needed")
    tickets = ", ".join(e.tickets) or "—"
    cells = [
        _md(f"""
# {entry} — {e.title}

Tickets: {tickets} · code: `{e.code}` · generated by `python -m insar_wetlands.colab {entry}`; do not edit by hand.

**Run all.** The notebook mounts the Drive, checks out `REF`, installs, runs the entry through the register and
writes the run record to Drive `insar_rzecin/runs/{entry}/`. The cube and the crops outside 2022–2024 are read from
`insar_rzecin/mac_backup/` (read-only: never write there). Outputs go where the entry's code says (Drive), never into
this public repository."""),
        _code(f'REF = "{ref}"          # branch or commit to run; the run record keeps the exact commit'),
        *([_md("**Conda tools.** This entry needs conda-forge packages. The next cell installs conda once; the "
               "runtime then **restarts by itself**. After the restart, *Run all* again: the cell sees conda and "
               "goes on."),
           _code("!pip install -q condacolab\nimport condacolab\ncondacolab.install()"),
           _code(f"!mamba install -q -y -c conda-forge {conda} {CONDA_BASE}")] if conda else []),
        _code(f"""
from google.colab import drive
drive.mount("/content/drive")
import os, subprocess
if not os.path.isdir("/content/SAr-adapted"):
    subprocess.run(["git", "clone", "-q", "{REPO_URL}", "/content/SAr-adapted"], check=True)
os.chdir("/content/SAr-adapted")
subprocess.run(["git", "fetch", "-q", "origin"], check=True)
subprocess.run(["git", "checkout", "-q", REF], check=True)
subprocess.run(["git", "pull", "-q", "--ff-only"], check=False)
print(subprocess.run(["git", "log", "-1", "--oneline"], capture_output=True, text=True).stdout)"""),
        _code(f"!bash colab/setup.sh {'conda' if conda else extra}".strip() + (f"\n!pip install -q {pip}" if pip else "")),
        *([_md("**Secrets.** Add " + ", ".join(f"`{k}`" for k in secrets.split()) + " in Colab's key manager (🔑 in "
               "the left bar) and switch on *Notebook access*. The next cell passes them to the run as environment "
               "variables (a subprocess cannot read the key manager); nothing is printed or saved."),
           _code("from google.colab import userdata\nimport os\n"
                 f"for k in {secrets.split()!r}:\n"
                 "    try:\n        os.environ[k] = userdata.get(k)\n"
                 "    except Exception as e:\n"
                 "        raise SystemExit(f'add the secret {k} in the key manager and give this notebook access ({type(e).__name__})')\n"
                 "print('secrets set:', ', '.join(" + repr(secrets.split()) + "))")] if secrets else []),
        _code(f"!PYTHONPATH=src python -m insar_wetlands.register run {entry}" + (f" -- {args}" if args else "")),
        _code(f"""
import glob, json
last = sorted(glob.glob("/content/drive/MyDrive/insar_rzecin/runs/{entry}/*/manifest.json"))[-1]
m = json.load(open(last)); print(last); print(json.dumps({{k: m[k] for k in ("exit_code", "duration_s", "git")}}, indent=1))
print(len(m["outputs_written"]), "output files written")"""),
    ]
    return {"cells": cells, "metadata": {"colab": {"provenance": []}, "kernelspec": {"name": "python3",
            "display_name": "Python 3"}, "language_info": {"name": "python"}}, "nbformat": 4, "nbformat_minor": 5}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m insar_wetlands.colab", description=__doc__.splitlines()[0])
    ap.add_argument("entry")
    ap.add_argument("--ref", default="fusion-x062")
    ap.add_argument("--extra", default="", help="setup.sh extra: '' or 'acquisition'")
    ap.add_argument("--pip", default="", help="extra pip packages for this launcher only (e.g. heavy SAR tools)")
    ap.add_argument("--args", default="", help="arguments passed to the entry")
    ap.add_argument("--conda", default="", help="conda-forge packages (installed through condacolab; one restart)")
    ap.add_argument("--secrets", default="", help="Colab key-manager names passed to the run as environment variables")
    a = ap.parse_args(argv)
    out = REPO / "colab" / f"{a.entry}.ipynb"
    out.write_text(json.dumps(launcher(a.entry, a.ref, a.extra, a.pip, a.args, a.conda, a.secrets), indent=1, ensure_ascii=False) + "\n")
    print(f"wrote {out.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
